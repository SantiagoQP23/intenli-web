export function useTranslations(lang: Lang) {
  return (key: UiKey, vars: Record<string, string> = {}) =>
    (ui[lang][key] as string).replace(/\{(\w+)\}/g, (_, k: string) => vars[k] ?? `{${k}}`);
}
